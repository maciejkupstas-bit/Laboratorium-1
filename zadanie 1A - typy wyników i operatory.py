# Zadanie 1A – typy wyników i operatory

print("A) Operatory arytmetyczne")
print("1 + 2 =", 1 + 2, "| typ:", type(1 + 2))
print("1 + 4.5 =", 1 + 4.5, "| typ:", type(1 + 4.5))
print("3 / 2 =", 3 / 2, "| typ:", type(3 / 2))
print("4 / 2 =", 4 / 2, "| typ:", type(4 / 2))
print("3 // 2 =", 3 // 2, "| typ:", type(3 // 2))
print("-3 // 2 =", -3 // 2, "| typ:", type(-3 // 2))
print("11 % 2 =", 11 % 2, "| typ:", type(11 % 2))
print("2 ** 10 =", 2 ** 10, "| typ:", type(2 ** 10))
print("8 ** (1 / 3) =", 8 ** (1 / 3), "| typ:", type(8 ** (1 / 3)))

print("\nB) Funkcje konwertujące")
print("int(3.0) =", int(3.0), "| typ:", type(int(3.0)))
print("float(3) =", float(3), "| typ:", type(float(3)))
print('float("3") =', float("3"), "| typ:", type(float("3")))
print("str(12.4) =", str(12.4), "| typ:", type(str(12.4)))
print("bool(0) =", bool(0), "| typ:", type(bool(0)))